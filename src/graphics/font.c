void font_draw_char(
    uint64_t x,
    uint64_t y,
    uint32_t color,
    char character
)
{
    uint8_t c = (uint8_t)character;

    /* 非 ASCII 可打印字符没有对应字形，统一显示问号。 */
    if (c < 0x20 || c > 0x7E)
    {
        c = '?';
    }

    const uint8_t *glyph =
        font[c - 0x20];

    /* 逐行读取位图；空白位不写像素，因此保留原背景。 */
    for (uint64_t py = 0;
         py < FONT_HEIGHT;
         py++)
    {
        for (uint64_t px = 0;
             px < FONT_WIDTH;
             px++)
        {
            if (glyph[py] & (0x80 >> px))
            {
                framebuffer_put_pixel(
                    x + px,
                    y + py,
                    color
                );
            }
        }
    }
}

void font_draw_string(
    uint64_t x,
    uint64_t y,
    uint32_t color,
    const char *text
)
{
    /* 字符串不包含换行语义，调用者负责处理 Console 控制字符。 */
    while (*text)
    {
        font_draw_char(
            x,
            y,
            color,
            *text
        );

        x += FONT_SPACING;
        text++;
    }
}
